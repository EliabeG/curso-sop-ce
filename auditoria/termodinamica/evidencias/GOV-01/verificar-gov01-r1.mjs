import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
const dir=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(dir,'../../../..');
const sha=x=>crypto.createHash('sha256').update(x).digest('hex');
const before=await fs.readFile(path.join(dir,'e1-termodinamica.antes.html'),'utf8');
const after=await fs.readFile(path.join(root,'modulos/e1-termodinamica.html'),'utf8');
const introBefore=await fs.readFile(path.join(dir,'introducao-antes.html'),'utf8');
const introAfter=await fs.readFile(path.join(dir,'introducao-depois.html'),'utf8');
const changes=JSON.parse(await fs.readFile(path.join(dir,'mudancas-r1.json'),'utf8'));
const base=JSON.parse(await fs.readFile(path.join(dir,'base.json'),'utf8'));
assert.equal(sha(before),base.sha256.html);
assert.equal(before.split(introBefore).length,2);
assert.equal(before.split(changes.lead.antes).length,3);
assert.equal(after,before.replaceAll(changes.lead.antes,changes.lead.depois).replace(introBefore,introAfter),'Alteracao fora dos dois leads e da introducao autorizada');
const articles=/<article\b[^>]*\bid="(?:q|cr|av)-e1-\d{2}"[^>]*>[\s\S]*?<\/article>/g;
const qa=[...before.matchAll(articles)].map(m=>m[0]),qb=[...after.matchAll(articles)].map(m=>m[0]);
assert.equal(qa.length,190);assert.deepEqual(qb,qa,'Banco de questoes alterado');
const idsBefore=[...before.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
const ids=[...after.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(ids.length,new Set(ids).size,'IDs duplicados');
assert.deepEqual(ids.filter(id=>!idsBefore.includes(id)),changes.ids_adicionados);
for(const id of idsBefore)assert(ids.includes(id),'ID anterior removido: '+id);
const links=[...introAfter.matchAll(/href="#([^"]+)"/g)].map(m=>m[1]);
for(const target of links)assert(idsBefore.includes(target),'Destino deve existir antes da mudanca: '+target);
const rows=[...introAfter.matchAll(/<tr id="competencia-c(\d{2})">([\s\S]*?)<\/tr>/g)];
assert.equal(rows.length,10);
for(let i=0;i<10;i++){
 assert.equal(rows[i][1],String(i+1).padStart(2,'0'));
 assert.equal((rows[i][2].match(/scope="row"/g)||[]).length,1);
 assert.equal((rows[i][2].match(/data-rotulo=/g)||[]).length,4);
 assert(rows[i][2].includes('Em desenvolvimento:'));
}
for(const [file,key] of [['assets/registro.js','registro'],['assets/curso.js','curso_js'],['assets/curso.css','curso_css']])assert.equal(sha(await fs.readFile(path.join(root,file))),base.sha256[key],'Arquivo compartilhado alterado: '+file);
const questions30=qb.filter(q=>/id="q-e1-/.test(q));
assert.equal(questions30.length,30);
const gabarito=questions30.map(q=>/data-gabarito="([A-E])"/.exec(q)[1]).join('');
assert.equal(gabarito,'CBECCDEABEDCCEAADDAAECCCEBAECB');
export const resultado={id:'GOV-01',rodada:1,metodo:'Verificacao estatica integral; sem ensaio de navegador',sha256:{html_antes:sha(before),html_depois:sha(after),registro:base.sha256.registro,curso_js:base.sha256.curso_js,curso_css:base.sha256.curso_css},escopo:'Duas ocorrencias do lead e uma introducao substituidas; demais bytes identicos',banco:{artigos_identicos:190,BAN01_identico:true,gabarito},ids:{antes:idsBefore.length,depois:ids.length,adicionados:changes.ids_adicionados,duplicados:0},vinculos_introduzidos:links.length,vinculos_sem_destino:0,resultados_publicados:rows.map(r=>'C'+r[1]),arquivos_compartilhados_inalterados:true};
