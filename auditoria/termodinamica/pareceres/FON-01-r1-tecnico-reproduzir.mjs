const output=path.join(here,'FON-01-r1-tecnico-autor-reproduzido.json');
let writes=0;
const safeFs={...fs,writeFile:async(target,content,...rest)=>{if(path.resolve(target)!==path.join(base,'verificacao-r1.json'))throw Error('Escrita fora da saída declarada');writes++;return fs.writeFile(output,content,...rest);}};
const AsyncFunction=Object.getPrototypeOf(async function(){}).constructor;
await new AsyncFunction('fs','path','fileURLToPath','createHash','parseHtml','isInventoryArticle','validateInventory','base','root',executable)(safeFs,path,fileURLToPath,createHash,validator.parseHtml,validator.isInventoryArticle,validator.validateInventory,base,root);
if(writes!==1)throw Error('Contagem inesperada de escritas');
const reproduced=await fs.readFile(output),original=await fs.readFile(path.join(base,'verificacao-r1.json'));
